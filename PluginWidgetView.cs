    internal static class PluginWidgetView
    {
        internal static Border Create(PluginWidget widget, Func<string, Task> invoke)
        {
            if (widget == null) throw new ArgumentNullException("widget");
            bool indicator = widget.Kind == "indicator";
            bool tile = widget.Kind == "tile";
            if (!indicator && !tile && widget.Kind != "card")
                throw new ArgumentException("Unknown widget kind.", "widget");

            Border frame = new Border
            {
                Background = FluentUi.Surface, BorderBrush = FluentUi.BorderColor,
                BorderThickness = new Thickness(1), CornerRadius = new CornerRadius(indicator ? 8 : 12),
                Padding = new Thickness(indicator ? 8 : 12),
                MaxWidth = indicator ? 360 : tile ? 200 : 440,
                VerticalAlignment = VerticalAlignment.Top, Tag = widget.Id
            };
            AutomationProperties.SetName(frame, widget.Title);
            StackPanel body = new StackPanel();
            frame.Child = body;

            TextBlock title = Literal(widget.Title, indicator ? 12 : tile ? 13 : 15, FluentUi.Foreground);
            title.FontWeight = FontWeights.SemiBold;
            title.Margin = new Thickness(0, 0, 0, indicator ? 4 : 8);
            body.Children.Add(title);

            // All elements are generated by the host, never by parsing plugin markup.
            Panel elements = indicator ? (Panel)new WrapPanel() : new StackPanel();
            body.Children.Add(elements);
            List<Button> actions = new List<Button>();
            TextBlock error = Literal("Не удалось выполнить команду.", 12, FluentUi.Amber);
            error.Margin = new Thickness(0, 6, 0, 0);
            error.Visibility = Visibility.Collapsed;
            bool busy = false;
            foreach (PluginWidgetElement element in widget.Elements)
            {
                FrameworkElement view;
                switch (element.Type)
                {
                    case "text":
                        view = Literal(element.Label, 12, FluentUi.Secondary);
                        break;
                    case "metric":
                        view = Metric(element, tile, indicator);
                        break;
                    case "progress":
                        view = Progress(element);
                        break;
                    case "action":
                        string command = element.CommandId;
                        Button action = new Button
                        {
                            Content = Literal(element.Label, 12, FluentUi.Foreground),
                            Background = FluentUi.SurfaceRaised, Foreground = FluentUi.Foreground,
                            MinHeight = indicator ? 26 : 30, Padding = new Thickness(8, 4, 8, 4),
                            IsEnabled = invoke != null, Tag = command
                        };
                        AutomationProperties.SetName(action, element.Label);
                        actions.Add(action);
                        action.Click += async delegate
                        {
                            if (busy || invoke == null) return;
                            busy = true;
                            error.Visibility = Visibility.Collapsed;
                            foreach (Button button in actions) button.IsEnabled = false;
                            try { await invoke(command); }
                            catch (Exception) { error.Visibility = Visibility.Visible; }
                            finally
                            {
                                busy = false;
                                foreach (Button button in actions) button.IsEnabled = true;
                            }
                        };
                        view = action;
                        break;
                    default: throw new ArgumentException("Unknown widget element.", "widget");
                }
                if (indicator)
                {
                    view.MaxWidth = 200;
                    view.Margin = new Thickness(0, 0, 8, 3);
                }
                else if (elements.Children.Count != 0) view.Margin = new Thickness(0, 6, 0, 0);
                elements.Children.Add(view);
            }
            body.Children.Add(error);
            return frame;
        }

        private static TextBlock Literal(string value, double size, Brush color)
        {
            return new TextBlock
            {
                Text = value, FontSize = size, Foreground = color,
                TextWrapping = TextWrapping.Wrap, VerticalAlignment = VerticalAlignment.Center
            };
        }

        private static FrameworkElement Metric(PluginWidgetElement element, bool tile, bool indicator)
        {
            TextBlock label = Literal(element.Label, 12, FluentUi.Secondary);
            TextBlock value = Literal(element.Value, tile ? 20 : indicator ? 12 : 14, FluentUi.Foreground);
            value.FontWeight = FontWeights.SemiBold;
            if (tile)
            {
                StackPanel stack = new StackPanel();
                stack.Children.Add(label); stack.Children.Add(value);
                return stack;
            }
            Grid row = new Grid();
            row.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(2, GridUnitType.Star) });
            row.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(3, GridUnitType.Star) });
            value.TextAlignment = TextAlignment.Right;
            value.Margin = new Thickness(8, 0, 0, 0);
            Grid.SetColumn(value, 1);
            row.Children.Add(label); row.Children.Add(value);
            return row;
        }

        private static FrameworkElement Progress(PluginWidgetElement element)
        {
            StackPanel stack = new StackPanel();
            TextBlock label = Literal(element.Label, 12, FluentUi.Secondary);
            stack.Children.Add(label);
            stack.MinWidth = 64;
            ProgressBar bar = new ProgressBar
            {
                Minimum = 0, Maximum = 100, Value = element.Percent.Value,
                Height = 8, Margin = new Thickness(0, 4, 0, 0),
                Foreground = FluentUi.Accent, Background = FluentUi.SurfaceRaised,
                BorderThickness = new Thickness(0)
            };
            AutomationProperties.SetName(bar, element.Label);
            stack.Children.Add(bar);
            return stack;
        }
    }

    // Two-by-two widget groups. The host owns all positions and spans.
    internal sealed class PluginWidgetWorkspace
    {
        private sealed class WidgetGroup
        {
            internal int Number, Order = Int32.MaxValue;
            internal string Zone, Title;
            internal Border Card;
            internal Grid Cells;
            internal TextBlock Heading;
        }

        private sealed class Placement
        {
            internal string PluginId, Version, WidgetId, Title, Kind, Size;
            internal int ProcessId, Revision, Row, Column;
            internal bool Busy, Stale, RestorePending;
            internal ContentControl Host;
            internal WidgetGroup Group;
            internal PluginWidget Snapshot;
        }

        private static readonly string[] Sizes = { "full", "half-horizontal", "half-vertical", "quarter" };
        private readonly List<Placement> entries = new List<Placement>();
        private readonly List<WidgetGroup> groups = new List<WidgetGroup>();
        private readonly Func<string, PluginRuntimeState> state;
        private readonly Func<string, string, bool, Task<PluginWidgetSnapshot>> read;
        private readonly Func<string, string, int, string, Task> invoke;
        private readonly Action changed;
        private Brush groupBackground = FluentUi.Surface, groupBorder = FluentUi.BorderColor;
        private int nextGroupNumber;
        private Dictionary<string, StackPanel> board;
        private string[] zones;
        private Func<string, string> zoneLabel;
        private Func<string, string> renameGroup;
        private Func<bool> canEdit = delegate { return true; };
        private string defaultZone = "top-left";
        private WidgetGroup draggingGroup;
        internal const string GroupDragFormat = "AppShelf.WidgetGroup";
        internal WrapPanel Surface { get; private set; }
        internal bool HasWidgets { get { return entries.Count != 0; } }

        internal PluginWidgetWorkspace(Func<string, PluginRuntimeState> state,
            Func<string, string, bool, Task<PluginWidgetSnapshot>> read,
            Func<string, string, int, string, Task> invoke, Action changed)
        {
            this.state = state; this.read = read; this.invoke = invoke; this.changed = changed;
            Surface = new WrapPanel { Visibility = Visibility.Collapsed,
                HorizontalAlignment = HorizontalAlignment.Stretch, Margin = new Thickness(0, 0, 0, 8) };
            Surface.SizeChanged += delegate { foreach (WidgetGroup group in groups) ResizeGroup(group); };
        }

        internal void ApplyAppearance(Brush background, Brush border)
        {
            groupBackground = background; groupBorder = border;
            foreach (WidgetGroup group in groups)
            { group.Card.Background = background; group.Card.BorderBrush = border; }
        }

        internal bool Contains(string pluginId, string widgetId)
        {
            return entries.Exists(delegate(Placement p) { return p.PluginId == pluginId && p.WidgetId == widgetId; });
        }

        private static bool Current(PluginRuntimeState state, string version, int processId)
        {
            return state != null && state.Status == "running" && state.Version == version &&
                processId > 0 && state.ProcessId == processId;
        }

        private static int Rows(string size) { return size == "full" || size == "half-vertical" ? 2 : 1; }
        private static int Columns(string size) { return size == "full" || size == "half-horizontal" ? 2 : 1; }

        private static string SizeLabel(string size)
        {
            switch (size)
            {
                case "full": return "Целая группа";
                case "half-horizontal": return "Половина горизонтальная";
                case "half-vertical": return "Половина вертикальная";
                default: return "Четверть группы";
            }
        }

        private bool FindSpace(WidgetGroup group, string size, Placement except, out int row, out int column)
        {
            int height = Rows(size), width = Columns(size);
            for (row = 0; row <= 2 - height; row++)
                for (column = 0; column <= 2 - width; column++)
                {
                    bool occupied = false;
                    foreach (Placement p in entries)
                    {
                        if (p == except || p.Group != group) continue;
                        if (row < p.Row + Rows(p.Size) && p.Row < row + height &&
                            column < p.Column + Columns(p.Size) && p.Column < column + width)
                        { occupied = true; break; }
                    }
                    if (!occupied) return true;
                }
            row = column = 0;
            return false;
        }

        internal void ConfigureBoard(string[] zoneKeys, Func<string, string> label,
            Func<string, string> rename, Func<bool> editable)
        {
            zones = zoneKeys; zoneLabel = label; renameGroup = rename; canEdit = editable;
        }

        private static void DetachCard(WidgetGroup group)
        {
            Panel parent = group.Card.Parent as Panel;
            if (parent != null) parent.Children.Remove(group.Card);
        }

        internal void DetachBoard()
        {
            foreach (WidgetGroup group in groups) DetachCard(group);
            board = null;
        }

        internal void AttachBoard(Dictionary<string, StackPanel> hosts, string fallback)
        {
            board = hosts; defaultZone = fallback;
            List<WidgetGroup> ordered = new List<WidgetGroup>(groups);
            ordered.Sort(delegate(WidgetGroup a, WidgetGroup b) {
                int order = a.Order.CompareTo(b.Order);
                return order != 0 ? order : a.Number.CompareTo(b.Number);
            });
            foreach (WidgetGroup group in ordered)
            {
                DetachCard(group);
                StackPanel host;
                if (!hosts.TryGetValue(group.Zone ?? defaultZone, out host)) host = hosts[defaultZone];
                host.Children.Insert(Math.Min(group.Order, host.Children.Count), group.Card);
            }
        }

        internal void FitBoard(double available)
        {
            if (board == null) return;
            foreach (WidgetGroup group in groups)
            {
                group.Card.Width = Math.Max(1, Math.Min(available, 400));
                group.Card.Margin = new Thickness(0, 0, 0, 8);
            }
        }

        private void ResizeGroup(WidgetGroup group)
        {
            if (board != null) return;
            double available = Surface.ActualWidth > 8 ? Surface.ActualWidth - 8 : 400;
            group.Card.Width = Math.Max(1, Math.Min(available, 400));
        }

        private void RememberZoneOrder(StackPanel host)
        {
            if (host == null) return;
            foreach (WidgetGroup group in groups)
                if (Object.ReferenceEquals(group.Card.Parent, host))
                    group.Order = host.Children.IndexOf(group.Card);
        }

        private void MoveGroupBy(WidgetGroup group, int delta)
        {
            if (!canEdit() || board == null) return;
            StackPanel host = group.Card.Parent as StackPanel;
            if (host == null) return;
            int from = host.Children.IndexOf(group.Card), to = from + delta;
            if (from < 0 || to < 0 || to >= host.Children.Count) return;
            host.Children.RemoveAt(from); host.Children.Insert(to, group.Card);
            RememberZoneOrder(host); changed();
        }

        private void MoveGroupToZone(WidgetGroup group, string zone)
        {
            if (!canEdit() || board == null || !groups.Contains(group) || !board.ContainsKey(zone)) return;
            StackPanel previous = group.Card.Parent as StackPanel;
            StackPanel target = board[zone];
            if (Object.ReferenceEquals(previous, target)) return;
            DetachCard(group); target.Children.Add(group.Card);
            group.Zone = zone;
            RememberZoneOrder(previous); RememberZoneOrder(target);
            changed();
        }

        internal bool IsGroupDrag(IDataObject data)
        {
            return draggingGroup != null && data.GetDataPresent(GroupDragFormat) &&
                Object.Equals(data.GetData(GroupDragFormat), draggingGroup.Number.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }

        internal bool CanDropGroup(IDataObject data, string zone)
        {
            return IsGroupDrag(data) && board != null && canEdit() && board.ContainsKey(zone) &&
                !Object.ReferenceEquals(draggingGroup.Card.Parent, board[zone]);
        }

        internal bool DropGroup(IDataObject data, string zone)
        {
            if (!CanDropGroup(data, zone)) return false;
            MoveGroupToZone(draggingGroup, zone); return true;
        }

        private void ConfigureGroupMenu(WidgetGroup group)
        {
            if (zones == null) return;
            ContextMenu menu = new ContextMenu();
            menu.Opened += delegate
            {
                menu.Items.Clear();
                MenuItem rename = new MenuItem { Header = "Переименовать группу…", IsEnabled = canEdit() };
                rename.Click += delegate {
                    string value = renameGroup(group.Title);
                    if (!String.IsNullOrWhiteSpace(value) && value.Trim().Length <= 100 && canEdit())
                    { group.Title = value.Trim(); group.Heading.Text = group.Title; changed(); }
                };
                menu.Items.Add(rename);
                MenuItem collapse = new MenuItem { Header = group.Cells.Visibility == Visibility.Visible ? "Свернуть группу" : "Развернуть группу", IsEnabled = canEdit() };
                collapse.Click += delegate {
                    if (!canEdit()) return;
                    group.Cells.Visibility = group.Cells.Visibility == Visibility.Visible ? Visibility.Collapsed : Visibility.Visible;
                    changed();
                };
                menu.Items.Add(collapse);
                StackPanel host = group.Card.Parent as StackPanel;
                int index = host == null ? -1 : host.Children.IndexOf(group.Card);
                MenuItem up = new MenuItem { Header = "Переместить выше", IsEnabled = canEdit() && index > 0 };
                up.Click += delegate { MoveGroupBy(group, -1); }; menu.Items.Add(up);
                MenuItem down = new MenuItem { Header = "Переместить ниже", IsEnabled = canEdit() && host != null && index >= 0 && index + 1 < host.Children.Count };
                down.Click += delegate { MoveGroupBy(group, 1); }; menu.Items.Add(down);
                MenuItem location = new MenuItem { Header = "Расположение", IsEnabled = canEdit() && board != null };
                foreach (string key in zones)
                {
                    string target = key;
                    MenuItem choice = new MenuItem { Header = zoneLabel(key), IsCheckable = true,
                        IsChecked = board != null && Object.ReferenceEquals(group.Card.Parent, board[key]) };
                    choice.Click += delegate { MoveGroupToZone(group, target); };
                    location.Items.Add(choice);
                }
                menu.Items.Add(location);
            };
            group.Heading.ContextMenu = menu;
            group.Heading.ToolTip = "Перетащите группу в другую зону или откройте меню правой кнопкой.";
            Point start = new Point();
            bool candidate = false;
            group.Heading.PreviewMouseLeftButtonDown += delegate(object sender, MouseButtonEventArgs e)
            { start = e.GetPosition(group.Heading); candidate = true; };
            group.Heading.PreviewMouseLeftButtonUp += delegate { candidate = false; };
            group.Heading.MouseMove += delegate(object sender, MouseEventArgs e)
            {
                if (!candidate || e.LeftButton != MouseButtonState.Pressed || !canEdit() || board == null) return;
                Point now = e.GetPosition(group.Heading);
                if (Math.Abs(now.X - start.X) < SystemParameters.MinimumHorizontalDragDistance &&
                    Math.Abs(now.Y - start.Y) < SystemParameters.MinimumVerticalDragDistance) return;
                candidate = false;
                draggingGroup = group;
                try { DragDrop.DoDragDrop(group.Heading,
                    new DataObject(GroupDragFormat, group.Number.ToString(System.Globalization.CultureInfo.InvariantCulture)), DragDropEffects.Move); }
                finally { draggingGroup = null; }
            };
        }

        private WidgetGroup NewGroup()
        {
            WidgetGroup group = new WidgetGroup { Number = ++nextGroupNumber, Zone = defaultZone };
            group.Title = "Виджеты " + group.Number;
            group.Cells = new Grid { Height = 280, ClipToBounds = true };
            for (int i = 0; i < 2; i++)
            {
                group.Cells.RowDefinitions.Add(new RowDefinition { Height = new GridLength(1, GridUnitType.Star) });
                group.Cells.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(1, GridUnitType.Star), MinWidth = 0 });
            }
            StackPanel body = new StackPanel();
            TextBlock title = new TextBlock { Text = group.Title, Foreground = FluentUi.Secondary,
                FontSize = 13, FontWeight = FontWeights.SemiBold, Margin = new Thickness(4, 0, 4, 6) };
            body.Children.Add(title); body.Children.Add(group.Cells);
            group.Card = new Border { Child = body, Padding = new Thickness(6), Margin = new Thickness(0, 0, 8, 8),
                Background = groupBackground, BorderBrush = groupBorder, BorderThickness = new Thickness(1),
                CornerRadius = new CornerRadius(13), VerticalAlignment = VerticalAlignment.Top };
            group.Heading = title;
            ConfigureGroupMenu(group);
            groups.Add(group);
            if (zones == null) Surface.Children.Add(group.Card);
            ResizeGroup(group);
            return group;
        }

        private void RemoveEmptyGroup(WidgetGroup group)
        {
            if (entries.Exists(delegate(Placement p) { return p.Group == group; })) return;
            StackPanel parent = group.Card.Parent as StackPanel;
            groups.Remove(group); DetachCard(group); RememberZoneOrder(parent);
        }

        private void Position(Placement entry, WidgetGroup group, string size, int row, int column)
        {
            WidgetGroup old = entry.Group;
            if (old != null && old != group) old.Cells.Children.Remove(entry.Host);
            entry.Group = group; entry.Size = size; entry.Row = row; entry.Column = column;
            Grid.SetRow(entry.Host, row); Grid.SetColumn(entry.Host, column);
            Grid.SetRowSpan(entry.Host, Rows(size)); Grid.SetColumnSpan(entry.Host, Columns(size));
            if (!group.Cells.Children.Contains(entry.Host)) group.Cells.Children.Add(entry.Host);
            if (old != null && old != group) RemoveEmptyGroup(old);
        }

        internal bool Add(string pluginId, string version, PluginWidgetSnapshot snapshot, string widgetId)
        {
            if (!canEdit() || entries.Count >= 32 || Contains(pluginId, widgetId) ||
                !Current(state(pluginId), version, snapshot.ProcessId)) return false;
            PluginWidget widget = Array.Find(snapshot.Widgets, delegate(PluginWidget item) { return item.Id == widgetId; });
            if (widget == null || !widget.SupportsSize(widget.PreferredSize)) return false;
            Placement entry = new Placement { PluginId = pluginId, Version = version, WidgetId = widget.Id,
                Title = widget.Title, Kind = widget.Kind, ProcessId = snapshot.ProcessId, Snapshot = widget };
            WirePlacement(entry);
            WidgetGroup destination = null;
            int targetRow = 0, targetColumn = 0;
            foreach (WidgetGroup group in groups)
                if (FindSpace(group, widget.PreferredSize, null, out targetRow, out targetColumn))
                { destination = group; break; }
            if (destination == null)
            { destination = NewGroup(); targetRow = targetColumn = 0; }
            entries.Add(entry);
            Position(entry, destination, widget.PreferredSize, targetRow, targetColumn);
            Render(entry, widget);
            Surface.Visibility = Visibility.Visible;
            changed();
            return Contains(pluginId, widgetId);
        }

        private void WirePlacement(Placement entry)
        {
            entry.Host = new ContentControl { Margin = new Thickness(4), ClipToBounds = true,
                HorizontalAlignment = HorizontalAlignment.Stretch, VerticalAlignment = VerticalAlignment.Stretch,
                HorizontalContentAlignment = HorizontalAlignment.Stretch, VerticalContentAlignment = VerticalAlignment.Stretch };
            ContextMenu menu = new ContextMenu();
            MenuItem refresh = new MenuItem { Header = "Обновить виджет" };
            refresh.Click += async delegate { await Refresh(entry); };
            MenuItem remove = new MenuItem { Header = "Убрать виджет" };
            remove.Click += delegate { Remove(entry); };
            MenuItem sizeMenu = new MenuItem { Header = "Размер" };
            MenuItem moveMenu = new MenuItem { Header = "Переместить в группу" };
            menu.Items.Add(refresh); menu.Items.Add(remove); menu.Items.Add(new Separator());
            menu.Items.Add(sizeMenu); menu.Items.Add(moveMenu);
            menu.Opened += delegate
            {
                sizeMenu.Items.Clear(); moveMenu.Items.Clear();
                foreach (string size in Sizes)
                {
                    string targetSize = size;
                    int row, column;
                    MenuItem item = new MenuItem { Header = SizeLabel(size), IsCheckable = true,
                        IsChecked = size == entry.Size, IsEnabled = canEdit() && entry.Snapshot.SupportsSize(size) &&
                        FindSpace(entry.Group, size, entry, out row, out column) };
                    item.Click += delegate { ChangeSize(entry, targetSize); };
                    sizeMenu.Items.Add(item);
                }
                foreach (WidgetGroup group in groups)
                {
                    WidgetGroup target = group;
                    int row, column;
                    MenuItem item = new MenuItem { Header = group.Title,
                        IsEnabled = canEdit() && group != entry.Group && FindSpace(group, entry.Size, entry, out row, out column) };
                    item.Click += delegate { Move(entry, target); };
                    moveMenu.Items.Add(item);
                }
                MenuItem newGroup = new MenuItem { Header = "В новую группу", IsEnabled = canEdit() };
                newGroup.Click += delegate { if (canEdit() && entries.Contains(entry)) Move(entry, NewGroup()); };
                moveMenu.Items.Add(new Separator()); moveMenu.Items.Add(newGroup);
            };
            entry.Host.ContextMenu = menu;
        }

        internal List<PluginWidgetGroupConfig> CaptureLayout()
        {
            if (groups.Count == 0) return null;
            List<PluginWidgetGroupConfig> result = new List<PluginWidgetGroupConfig>();
            foreach (WidgetGroup group in groups)
            {
                PluginWidgetGroupConfig saved = new PluginWidgetGroupConfig { Number = group.Number,
                    Title = group.Title, Zone = group.Zone ?? defaultZone, Order = group.Order,
                    Collapsed = group.Cells.Visibility == Visibility.Collapsed,
                    Widgets = new List<PluginWidgetPlacementConfig>() };
                foreach (Placement p in entries)
                    if (p.Group == group)
                        saved.Widgets.Add(new PluginWidgetPlacementConfig { PluginId = p.PluginId,
                            WidgetId = p.WidgetId, Version = p.Version, Title = p.Title, Size = p.Size,
                            Row = p.Row, Column = p.Column });
                result.Add(saved);
            }
            PluginWidgetGroupConfig.Validate(result);
            return result;
        }

        internal void RestoreLayout(List<PluginWidgetGroupConfig> saved)
        {
            PluginWidgetGroupConfig.Validate(saved);
            Clear();
            nextGroupNumber = 0;
            if (saved == null) return;
            foreach (PluginWidgetGroupConfig item in saved)
            {
                WidgetGroup group = NewGroup();
                group.Number = item.Number;
                group.Title = item.Title; group.Heading.Text = item.Title;
                group.Zone = item.Zone; group.Order = item.Order;
                group.Cells.Visibility = item.Collapsed ? Visibility.Collapsed : Visibility.Visible;
                foreach (PluginWidgetPlacementConfig p in item.Widgets)
                {
                    PluginWidgetElement[] message = new[] { new PluginWidgetElement { Type = "text",
                        Label = "Загрузите виджет для получения данных." } };
                    PluginWidget placeholder = new PluginWidget { Id = p.WidgetId, Title = p.Title,
                        Kind = p.Size == "quarter" ? "tile" : "card", Elements = message,
                        DefaultSize = p.Size, Layouts = new[] { new PluginWidgetLayout { Size = p.Size, Elements = message } } };
                    Placement entry = new Placement { PluginId = p.PluginId, Version = p.Version,
                        WidgetId = p.WidgetId, Title = p.Title, Kind = placeholder.Kind, Snapshot = placeholder,
                        RestorePending = true };
                    WirePlacement(entry);
                    entries.Add(entry);
                    Position(entry, group, p.Size, p.Row, p.Column);
                    Unavailable(entry, "Загрузите виджет для получения данных.");
                }
            }
            foreach (WidgetGroup group in groups) nextGroupNumber = Math.Max(nextGroupNumber, group.Number);
            Surface.Visibility = HasWidgets ? Visibility.Visible : Visibility.Collapsed;
        }

        internal bool Resize(string pluginId, string widgetId, string size)
        {
            Placement entry = entries.Find(delegate(Placement p) { return p.PluginId == pluginId && p.WidgetId == widgetId; });
            return entry != null && ChangeSize(entry, size);
        }

        private bool ChangeSize(Placement entry, string size)
        {
            int row, column;
            if (!canEdit() || !entries.Contains(entry) || !entry.Snapshot.SupportsSize(size) ||
                !FindSpace(entry.Group, size, entry, out row, out column)) return false;
            if (size == entry.Size) return true;
            Position(entry, entry.Group, size, row, column);
            if (entry.Stale) Unavailable(entry, "Виджет недоступен. Обновите его.");
            else Render(entry, entry.Snapshot);
            changed();
            return true;
        }

        private void Move(Placement entry, WidgetGroup target)
        {
            int row, column;
            if (!canEdit() || !entries.Contains(entry) || target == entry.Group ||
                !FindSpace(target, entry.Size, entry, out row, out column)) return;
            Position(entry, target, entry.Size, row, column);
            changed();
        }

        private void Display(Placement entry, PluginWidget widget, Func<string, Task> action)
        {
            Border view = PluginWidgetView.Create(widget, action);
            view.MaxWidth = Double.PositiveInfinity;
            view.VerticalAlignment = VerticalAlignment.Stretch;
            // Long lists stay inside their allocated cells rather than increasing group size.
            ScrollViewer scroll = new ScrollViewer { Content = view,
                HorizontalScrollBarVisibility = ScrollBarVisibility.Disabled,
                VerticalScrollBarVisibility = ScrollBarVisibility.Auto };
            entry.Host.Content = scroll;
        }

        private void Render(Placement entry, PluginWidget widget)
        {
            entry.Snapshot = widget;
            entry.Stale = false;
            int revision = ++entry.Revision;
            Display(entry, widget.ForSize(entry.Size), delegate(string command)
            {
                if (!entries.Contains(entry) || entry.Revision != revision ||
                    !Current(state(entry.PluginId), entry.Version, entry.ProcessId))
                    throw new InvalidOperationException("Виджет устарел.");
                return invoke(entry.PluginId, entry.Version, entry.ProcessId, command);
            });
        }

        private void Unavailable(Placement entry, string message)
        {
            entry.Stale = true;
            entry.Revision++;
            Display(entry, new PluginWidget { Id = entry.WidgetId,
                Title = entry.Title, Kind = entry.Size == "quarter" ? "tile" : "card", Elements = new[] {
                    new PluginWidgetElement { Type = "text", Label = message } } }, null);
        }

        internal void InvalidateStopped()
        {
            foreach (Placement entry in entries)
                if (!entry.Stale && !Current(state(entry.PluginId), entry.Version, entry.ProcessId))
                    Unavailable(entry, "Плагин недоступен. Запустите его и обновите виджет.");
        }

        private async Task Refresh(Placement entry)
        {
            if (!entries.Contains(entry) || entry.Busy) return;
            entry.Busy = true;
            try
            {
                bool explicitActivation = zones != null && entry.Stale;
                PluginWidgetSnapshot snapshot = await read(entry.PluginId, explicitActivation ? null : entry.Version, explicitActivation);
                if (!entries.Contains(entry)) return;
                PluginWidget widget = Array.Find(snapshot.Widgets, delegate(PluginWidget item) { return item.Id == entry.WidgetId; });
                string version = snapshot.Version ?? entry.Version;
                if (widget == null || !Current(state(entry.PluginId), version, snapshot.ProcessId))
                {
                    Unavailable(entry, "Виджет недоступен в текущем сеансе плагина.");
                    return;
                }
                entry.ProcessId = snapshot.ProcessId;
                entry.Version = version;
                entry.RestorePending = false;
                entry.Title = widget.Title;
                entry.Snapshot = widget;
                if (!widget.SupportsSize(entry.Size))
                {
                    Unavailable(entry, "Размер больше не поддерживается. Выберите другой размер и обновите.");
                    return;
                }
                Render(entry, widget);
            }
            catch (Exception error)
            {
                ConfigStore.Log(error);
                if (entries.Contains(entry)) Unavailable(entry, "Не удалось обновить виджет.");
            }
            finally { entry.Busy = false; }
        }

        private void Remove(Placement entry)
        {
            if (!canEdit() || !entries.Remove(entry)) return;
            entry.Revision++;
            entry.Group.Cells.Children.Remove(entry.Host);
            RemoveEmptyGroup(entry.Group);
            Surface.Visibility = HasWidgets ? Visibility.Visible : Visibility.Collapsed;
            changed();
        }

        internal void Clear()
        {
            DetachBoard(); entries.Clear(); groups.Clear(); Surface.Children.Clear(); Surface.Visibility = Visibility.Collapsed;
        }
    }

