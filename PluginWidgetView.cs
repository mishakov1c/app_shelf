    internal static class PluginWidgetView
    {
        internal static Border Create(PluginWidget widget, Func<string, Task> invoke)
        {
            if (widget == null) throw new ArgumentNullException("widget");
            bool indicator = widget.Kind == "indicator";
            bool tile = widget.Kind == "tile";
            if (!indicator && !tile && widget.Kind != "card")
                throw new ArgumentException("Unknown widget kind.", "widget");

            Border frame = new Border
            {
                Background = FluentUi.Surface, BorderBrush = FluentUi.BorderColor,
                BorderThickness = new Thickness(1), CornerRadius = new CornerRadius(indicator ? 8 : 12),
                Padding = new Thickness(indicator ? 8 : 12),
                MaxWidth = indicator ? 360 : tile ? 200 : 440,
                VerticalAlignment = VerticalAlignment.Top, Tag = widget.Id
            };
            AutomationProperties.SetName(frame, widget.Title);
            StackPanel body = new StackPanel();
            frame.Child = body;

            TextBlock title = Literal(widget.Title, indicator ? 12 : tile ? 13 : 15, FluentUi.Foreground);
            title.FontWeight = FontWeights.SemiBold;
            title.Margin = new Thickness(0, 0, 0, indicator ? 4 : 8);
            body.Children.Add(title);

            // All elements are generated by the host, never by parsing plugin markup.
            Panel elements = indicator ? (Panel)new WrapPanel() : new StackPanel();
            body.Children.Add(elements);
            List<Button> actions = new List<Button>();
            TextBlock error = Literal("Не удалось выполнить команду.", 12, FluentUi.Amber);
            error.Margin = new Thickness(0, 6, 0, 0);
            error.Visibility = Visibility.Collapsed;
            bool busy = false;
            foreach (PluginWidgetElement element in widget.Elements)
            {
                FrameworkElement view;
                switch (element.Type)
                {
                    case "text":
                        view = Literal(element.Label, 12, FluentUi.Secondary);
                        break;
                    case "metric":
                        view = Metric(element, tile, indicator);
                        break;
                    case "progress":
                        view = Progress(element);
                        break;
                    case "action":
                        string command = element.CommandId;
                        Button action = new Button
                        {
                            Content = Literal(element.Label, 12, FluentUi.Foreground),
                            Background = FluentUi.SurfaceRaised, Foreground = FluentUi.Foreground,
                            MinHeight = indicator ? 26 : 30, Padding = new Thickness(8, 4, 8, 4),
                            IsEnabled = invoke != null, Tag = command
                        };
                        AutomationProperties.SetName(action, element.Label);
                        actions.Add(action);
                        action.Click += async delegate
                        {
                            if (busy || invoke == null) return;
                            busy = true;
                            error.Visibility = Visibility.Collapsed;
                            foreach (Button button in actions) button.IsEnabled = false;
                            try { await invoke(command); }
                            catch (Exception) { error.Visibility = Visibility.Visible; }
                            finally
                            {
                                busy = false;
                                foreach (Button button in actions) button.IsEnabled = true;
                            }
                        };
                        view = action;
                        break;
                    default: throw new ArgumentException("Unknown widget element.", "widget");
                }
                if (indicator)
                {
                    view.MaxWidth = 200;
                    view.Margin = new Thickness(0, 0, 8, 3);
                }
                else if (elements.Children.Count != 0) view.Margin = new Thickness(0, 6, 0, 0);
                elements.Children.Add(view);
            }
            body.Children.Add(error);
            return frame;
        }

        private static TextBlock Literal(string value, double size, Brush color)
        {
            return new TextBlock
            {
                Text = value, FontSize = size, Foreground = color,
                TextWrapping = TextWrapping.Wrap, VerticalAlignment = VerticalAlignment.Center
            };
        }

        private static FrameworkElement Metric(PluginWidgetElement element, bool tile, bool indicator)
        {
            TextBlock label = Literal(element.Label, 12, FluentUi.Secondary);
            TextBlock value = Literal(element.Value, tile ? 20 : indicator ? 12 : 14, FluentUi.Foreground);
            value.FontWeight = FontWeights.SemiBold;
            if (tile)
            {
                StackPanel stack = new StackPanel();
                stack.Children.Add(label); stack.Children.Add(value);
                return stack;
            }
            Grid row = new Grid();
            row.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(2, GridUnitType.Star) });
            row.ColumnDefinitions.Add(new ColumnDefinition { Width = new GridLength(3, GridUnitType.Star) });
            value.TextAlignment = TextAlignment.Right;
            value.Margin = new Thickness(8, 0, 0, 0);
            Grid.SetColumn(value, 1);
            row.Children.Add(label); row.Children.Add(value);
            return row;
        }

        private static FrameworkElement Progress(PluginWidgetElement element)
        {
            StackPanel stack = new StackPanel();
            TextBlock label = Literal(element.Label, 12, FluentUi.Secondary);
            stack.Children.Add(label);
            stack.MinWidth = 64;
            ProgressBar bar = new ProgressBar
            {
                Minimum = 0, Maximum = 100, Value = element.Percent.Value,
                Height = 8, Margin = new Thickness(0, 4, 0, 0),
                Foreground = FluentUi.Accent, Background = FluentUi.SurfaceRaised,
                BorderThickness = new Thickness(0)
            };
            AutomationProperties.SetName(bar, element.Label);
            stack.Children.Add(bar);
            return stack;
        }
    }

