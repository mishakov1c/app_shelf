        internal PluginWidgetWorkspace(Func<string, PluginRuntimeState> state,
            Func<string, string, bool, Task<PluginWidgetSnapshot>> read,
            Func<string, string, int, string, Task> invoke, Action changed)
        {
            this.state = state; this.read = read; this.invoke = invoke; this.changed = changed;
            Surface = new WrapPanel { Visibility = Visibility.Collapsed,
                HorizontalAlignment = HorizontalAlignment.Stretch, Margin = new Thickness(0, 0, 0, 8) };
            Surface.SizeChanged += delegate { foreach (WidgetGroup group in groups) ResizeGroup(group); };
            indicatorPanel = new StackPanel { Orientation = Orientation.Horizontal };
            IndicatorHost = new ScrollViewer { Content = indicatorPanel, Visibility = Visibility.Collapsed,
                HorizontalScrollBarVisibility = ScrollBarVisibility.Auto, VerticalScrollBarVisibility = ScrollBarVisibility.Disabled,
                MaxHeight = 90, Margin = new Thickness(0, 4, 0, 0) };
        }

        internal void ConfigureIndicatorEditing(Func<bool> editable) { canEditIndicators = editable; }

        internal void ApplyAppearance(Brush background, Brush border)
        {
            groupBackground = background; groupBorder = border;
            foreach (WidgetGroup group in groups)
            { group.Card.Background = background; group.Card.BorderBrush = border; }
        }

        internal bool Contains(string pluginId, string widgetId)
        {
            return entries.Exists(delegate(Placement p) { return p.PluginId == pluginId && p.WidgetId == widgetId; });
        }

        private static bool Current(PluginRuntimeState state, string version, int processId)
        {
            return state != null && state.Status == "running" && state.Version == version &&
                processId > 0 && state.ProcessId == processId;
        }

        private static int Rows(string size) { return size == "full" || size == "half-vertical" ? 2 : 1; }
        private static int Columns(string size) { return size == "full" || size == "half-horizontal" ? 2 : 1; }

        private static string SizeLabel(string size)
        {
            switch (size)
            {
                case "full": return "Целая группа";
                case "half-horizontal": return "Половина горизонтальная";
                case "half-vertical": return "Половина вертикальная";
                default: return "Четверть группы";
            }
        }

        private bool CanOccupy(WidgetGroup group, string size, Placement except, int row, int column)
        {
            int height = Rows(size), width = Columns(size);
            if (row < 0 || column < 0 || row > 2 - height || column > 2 - width) return false;
            foreach (Placement p in entries)
            {
                if (p == except || p.Group != group) continue;
                if (row < p.Row + Rows(p.Size) && p.Row < row + height &&
                    column < p.Column + Columns(p.Size) && p.Column < column + width) return false;
            }
            return true;
        }

        private bool FindSpace(WidgetGroup group, string size, Placement except, out int row, out int column)
        {
            for (row = 0; row <= 2 - Rows(size); row++)
                for (column = 0; column <= 2 - Columns(size); column++)
                    if (CanOccupy(group, size, except, row, column)) return true;
            row = column = 0;
            return false;
        }

        internal void ConfigureBoard(string[] zoneKeys, Func<string, string> label,
            Func<string, string> rename, Func<bool> editable)
        {
            zones = zoneKeys; zoneLabel = label; renameGroup = rename; canEdit = editable;
        }

        private static void DetachCard(WidgetGroup group)
        {
            Panel parent = group.Card.Parent as Panel;
            if (parent != null) parent.Children.Remove(group.Card);
            group.Card.Visibility = Visibility.Visible;
            group.Card.RenderTransform = Transform.Identity;
        }

        internal void DetachBoard()
        {
            ClearWidgetDropPreview();
            foreach (WidgetGroup group in groups) DetachCard(group);
            board = null; canvasAttached = false;
        }

        internal List<KeyValuePair<string, Border>> CanvasCards()
        {
            List<KeyValuePair<string, Border>> result = new List<KeyValuePair<string, Border>>();
            foreach (WidgetGroup group in groups)
                result.Add(new KeyValuePair<string, Border>("widget:" + group.Number.ToString(System.Globalization.CultureInfo.InvariantCulture), group.Card));
            return result;
        }

        internal List<KeyValuePair<string, Border>> AttachCanvas()
        {
            canvasAttached = true;
            List<KeyValuePair<string, Border>> cards = new List<KeyValuePair<string, Border>>();
            foreach (WidgetGroup group in groups)
            {
                DetachCard(group);
                group.Heading.TextWrapping = TextWrapping.Wrap;
                group.Heading.TextTrimming = TextTrimming.None;
                AutomationProperties.SetName(group.Card, group.Title);
                cards.Add(new KeyValuePair<string, Border>("widget:" + group.Number.ToString(System.Globalization.CultureInfo.InvariantCulture), group.Card));
            }
            return cards;
        }

        internal string CanvasDragKey(IDataObject data)
        {
            return canvasAttached && IsGroupDrag(data) ? "widget:" + draggingGroup.Number.ToString(System.Globalization.CultureInfo.InvariantCulture) : null;
        }

        internal void AttachBoard(Dictionary<string, StackPanel> hosts, string fallback)
        {
            board = hosts; canvasAttached = false; defaultZone = fallback;
            List<WidgetGroup> ordered = new List<WidgetGroup>(groups);
            ordered.Sort(delegate(WidgetGroup a, WidgetGroup b) {
                int order = a.Order.CompareTo(b.Order);
                return order != 0 ? order : a.Number.CompareTo(b.Number);
            });
            foreach (WidgetGroup group in ordered)
            {
                DetachCard(group);
                group.Heading.TextWrapping = TextWrapping.Wrap;
                group.Heading.TextTrimming = TextTrimming.None;
                StackPanel host;
                if (!hosts.TryGetValue(group.Zone ?? defaultZone, out host)) host = hosts[defaultZone];
                host.Children.Insert(Math.Min(group.Order, host.Children.Count), group.Card);
            }
        }

        internal void FitBoard(double available)
        {
            if (board == null) return;
            foreach (WidgetGroup group in groups)
            {
                group.Card.Width = Math.Max(1, Math.Min(available, 400));
                group.Card.Margin = new Thickness(0, 0, 0, 8);
            }
        }

        private void ResizeGroup(WidgetGroup group)
        {
            if (board != null || canvasAttached) return;
            double available = Surface.ActualWidth > 8 ? Surface.ActualWidth - 8 : 400;
            group.Card.Width = Math.Max(1, Math.Min(available, 400));
        }

        private void RememberZoneOrder(StackPanel host)
        {
            if (host == null) return;
            foreach (WidgetGroup group in groups)
                if (Object.ReferenceEquals(group.Card.Parent, host))
                    group.Order = host.Children.IndexOf(group.Card);
        }

        private void MoveGroupBy(WidgetGroup group, int delta)
        {
            if (!canEdit() || board == null) return;
            StackPanel host = group.Card.Parent as StackPanel;
            if (host == null) return;
            int from = host.Children.IndexOf(group.Card), to = from + delta;
            if (from < 0 || to < 0 || to >= host.Children.Count) return;
            host.Children.RemoveAt(from); host.Children.Insert(to, group.Card);
            RememberZoneOrder(host); changed();
        }

        private void MoveGroupToZone(WidgetGroup group, string zone)
        {
            if (!canEdit() || board == null || !groups.Contains(group) || !board.ContainsKey(zone)) return;
            StackPanel previous = group.Card.Parent as StackPanel;
            StackPanel target = board[zone];
            if (Object.ReferenceEquals(previous, target)) return;
            DetachCard(group); target.Children.Add(group.Card);
            group.Zone = zone;
            RememberZoneOrder(previous); RememberZoneOrder(target);
            changed();
        }

        internal bool IsGroupDrag(IDataObject data)
        {
            return draggingGroup != null && data.GetDataPresent(GroupDragFormat) &&
                Object.Equals(data.GetData(GroupDragFormat), draggingGroup.Number.ToString(System.Globalization.CultureInfo.InvariantCulture));
        }

        internal bool CanDropGroup(IDataObject data, string zone)
        {
            return IsGroupDrag(data) && board != null && canEdit() && board.ContainsKey(zone) &&
                !Object.ReferenceEquals(draggingGroup.Card.Parent, board[zone]);
        }

        internal bool DropGroup(IDataObject data, string zone)
        {
            if (!CanDropGroup(data, zone)) return false;
            MoveGroupToZone(draggingGroup, zone); return true;
        }

        private static string DragKey(Placement entry)
        { return entry.PluginId + "/" + entry.WidgetId; }

        internal bool IsWidgetDrag(IDataObject data)
        {
            return draggingWidget != null && entries.Contains(draggingWidget) &&
                data.GetDataPresent(WidgetDragFormat) && Object.Equals(data.GetData(WidgetDragFormat), DragKey(draggingWidget));
        }

        private bool WidgetDropTarget(DragEventArgs e, out WidgetGroup group, out int row, out int column)
        {
            group = null; row = column = 0;
            if ((board == null && !canvasAttached) || !canEdit() || !IsWidgetDrag(e.Data)) return false;
            DependencyObject node = e.OriginalSource as DependencyObject;
            while (node != null)
            {
                Grid grid = node as Grid;
                if (grid != null)
                {
                    group = groups.Find(delegate(WidgetGroup candidate) { return candidate.Cells == grid; });
                    if (group != null) break;
                }
                try { node = VisualTreeHelper.GetParent(node); }
                catch (InvalidOperationException) { node = LogicalTreeHelper.GetParent(node); }
            }
            if (group == null || group.Cells.Visibility != Visibility.Visible) return false;
            Point point = e.GetPosition(group.Cells);
            if (point.X < 0 || point.Y < 0 || point.X > group.Cells.ActualWidth || point.Y > group.Cells.ActualHeight)
                return false;
            // Snap a span to the nearest valid top-left cell inside the 2x2 grid.
            row = Math.Min(2 - Rows(draggingWidget.Size), point.Y >= group.Cells.ActualHeight / 2 ? 1 : 0);
            column = Math.Min(2 - Columns(draggingWidget.Size), point.X >= group.Cells.ActualWidth / 2 ? 1 : 0);
            return CanOccupy(group, draggingWidget.Size, draggingWidget, row, column) &&
                (draggingWidget.Group != group || draggingWidget.Row != row || draggingWidget.Column != column);
        }

        internal void ClearWidgetDropPreview()
        {
            if (widgetDropGrid != null && widgetDropPreview != null) widgetDropGrid.Children.Remove(widgetDropPreview);
            widgetDropGrid = null; widgetDropPreview = null;
        }

        internal bool PreviewWidgetDrop(DragEventArgs e)
        {
            WidgetGroup group;
            int row, column;
            if (!WidgetDropTarget(e, out group, out row, out column))
            { ClearWidgetDropPreview(); return false; }
            if (widgetDropGrid != group.Cells || widgetDropPreview == null ||
                Grid.GetRow(widgetDropPreview) != row || Grid.GetColumn(widgetDropPreview) != column)
            {
                ClearWidgetDropPreview();
                widgetDropGrid = group.Cells;
                widgetDropPreview = new Border { BorderBrush = FluentUi.Accent, BorderThickness = new Thickness(2),
                    CornerRadius = new CornerRadius(8), Margin = new Thickness(3), IsHitTestVisible = false };
                Grid.SetRow(widgetDropPreview, row); Grid.SetColumn(widgetDropPreview, column);
                Grid.SetRowSpan(widgetDropPreview, Rows(draggingWidget.Size));
                Grid.SetColumnSpan(widgetDropPreview, Columns(draggingWidget.Size));
                Panel.SetZIndex(widgetDropPreview, 100);
                widgetDropGrid.Children.Add(widgetDropPreview);
            }
            return true;
        }

        internal bool DropWidget(DragEventArgs e)
        {
            WidgetGroup group;
            int row, column;
            bool accepted = WidgetDropTarget(e, out group, out row, out column);
            ClearWidgetDropPreview();
            return accepted && MoveWidget(draggingWidget.PluginId, draggingWidget.WidgetId, group.Number, row, column);
        }

        internal bool MoveWidget(string pluginId, string widgetId, int groupNumber, int row, int column)
        {
            Placement entry = entries.Find(delegate(Placement p) { return p.PluginId == pluginId && p.WidgetId == widgetId; });
            WidgetGroup group = groups.Find(delegate(WidgetGroup g) { return g.Number == groupNumber; });
            if (!canEdit() || entry == null || entry.Group == null || group == null ||
                !CanOccupy(group, entry.Size, entry, row, column)) return false;
            if (entry.Group == group && entry.Row == row && entry.Column == column) return true;
            Position(entry, group, entry.Size, row, column);
            changed();
            return true;
        }

        private static TextBlock DragGrip()
        {
            return new TextBlock { Text = "⋮⋮", FontSize = 19, Foreground = FluentUi.Secondary,
                Margin = new Thickness(8, 0, 4, 0), Cursor = Cursors.SizeAll, VerticalAlignment = VerticalAlignment.Center };
        }

        private void UpdateGroupHeight(WidgetGroup group)
        {
            int used = 1;
            foreach (Placement p in entries)
                if (p.Group == group) used = Math.Max(used, p.Row + Rows(p.Size));
            if (draggingWidget != null) used = 2;
            group.Cells.Height = 140 * used;
            group.Cells.RowDefinitions[0].Height = new GridLength(140);
            group.Cells.RowDefinitions[1].Height = new GridLength(used == 2 ? 140 : 0);
        }

        private void SetDropHints(bool visible)
        {
            foreach (Border hint in widgetDropHints)
            {
                Grid parent = hint.Parent as Grid;
                if (parent != null) parent.Children.Remove(hint);
            }
            widgetDropHints.Clear();
            foreach (WidgetGroup group in groups)
            {
                UpdateGroupHeight(group);
                if (!visible || draggingWidget == null || group.Cells.Visibility != Visibility.Visible) continue;
                for (int row = 0; row <= 2 - Rows(draggingWidget.Size); row++)
                    for (int col = 0; col <= 2 - Columns(draggingWidget.Size); col++)
                    {
                        if (!CanOccupy(group, draggingWidget.Size, draggingWidget, row, col) ||
                            (group == draggingWidget.Group && row == draggingWidget.Row && col == draggingWidget.Column)) continue;
                        Border hint = new Border { BorderBrush = FluentUi.Secondary, BorderThickness = new Thickness(1),
                            CornerRadius = new CornerRadius(8), Margin = new Thickness(4), IsHitTestVisible = false,
                            Opacity = 0.7 };
                        Grid.SetRow(hint, row); Grid.SetColumn(hint, col);
                        Grid.SetRowSpan(hint, Rows(draggingWidget.Size)); Grid.SetColumnSpan(hint, Columns(draggingWidget.Size));
                        group.Cells.Children.Add(hint); widgetDropHints.Add(hint);
                    }
            }
        }

        private void WireWidgetDrag(Placement entry, Border view)
        {
            if (zones == null) return;
            StackPanel body = view.Child as StackPanel;
            TextBlock heading = body == null || body.Children.Count == 0 ? null : body.Children[0] as TextBlock;
            if (heading == null) return;
            DockPanel header = new DockPanel { LastChildFill = true };
            TextBlock grip = DragGrip();
            grip.ToolTip = "Перетащите виджет в свободные ячейки.";
            DockPanel.SetDock(grip, Dock.Right);
            body.Children.RemoveAt(0);
            header.Children.Add(grip); header.Children.Add(heading);
            body.Children.Insert(0, header);
            Point start = new Point();
            bool candidate = false;
            grip.PreviewMouseLeftButtonDown += delegate(object sender, MouseButtonEventArgs e)
            { start = e.GetPosition(grip); candidate = true; grip.CaptureMouse(); };
            grip.PreviewMouseLeftButtonUp += delegate { candidate = false; grip.ReleaseMouseCapture(); };
            grip.MouseMove += delegate(object sender, MouseEventArgs e)
            {
                if (!candidate || e.LeftButton != MouseButtonState.Pressed || !canEdit() || (board == null && !canvasAttached) ||
                    !entries.Contains(entry)) return;
                Point now = e.GetPosition(grip);
                if (Math.Abs(now.X - start.X) < SystemParameters.MinimumHorizontalDragDistance &&
                    Math.Abs(now.Y - start.Y) < SystemParameters.MinimumVerticalDragDistance) return;
                candidate = false; grip.ReleaseMouseCapture(); draggingWidget = entry;
                try { SetDropHints(true); DragDrop.DoDragDrop(grip, new DataObject(WidgetDragFormat, DragKey(entry)), DragDropEffects.Move); }
                finally { draggingWidget = null; ClearWidgetDropPreview(); SetDropHints(false); }
            };
        }

        private void ConfigureGroupMenu(WidgetGroup group)
        {
            if (zones == null) return;
            ContextMenu menu = new ContextMenu();
            menu.Opened += delegate
            {
                menu.Items.Clear();
                MenuItem rename = new MenuItem { Header = "Переименовать группу…", IsEnabled = canEdit() };
                rename.Click += delegate {
                    string value = renameGroup(group.Title);
                    if (!String.IsNullOrWhiteSpace(value) && value.Trim().Length <= 100 && canEdit())
                    { group.Title = value.Trim(); UpdateGroupHeader(group); changed(); }
                };
                menu.Items.Add(rename);
                MenuItem collapse = new MenuItem { Header = group.Cells.Visibility == Visibility.Visible ? "Свернуть группу" : "Развернуть группу", IsEnabled = canEdit() };
                collapse.Click += delegate {
                    ToggleGroup(group);
                };
                menu.Items.Add(collapse);
                StackPanel host = group.Card.Parent as StackPanel;
                int index = host == null ? -1 : host.Children.IndexOf(group.Card);
                MenuItem up = new MenuItem { Header = "Переместить выше", IsEnabled = canEdit() && index > 0 };
                up.Click += delegate { MoveGroupBy(group, -1); }; menu.Items.Add(up);
                MenuItem down = new MenuItem { Header = "Переместить ниже", IsEnabled = canEdit() && host != null && index >= 0 && index + 1 < host.Children.Count };
                down.Click += delegate { MoveGroupBy(group, 1); }; menu.Items.Add(down);
                MenuItem location = new MenuItem { Header = "Расположение", IsEnabled = canEdit() && board != null };
                foreach (string key in zones)
                {
                    string target = key;
                    MenuItem choice = new MenuItem { Header = zoneLabel(key), IsCheckable = true,
                        IsChecked = board != null && Object.ReferenceEquals(group.Card.Parent, board[key]) };
                    choice.Click += delegate { MoveGroupToZone(group, target); };
                    location.Items.Add(choice);
                }
                menu.Items.Add(location);
            };
            group.Header.ContextMenu = menu;
            group.Heading.ContextMenu = menu;
            group.Grip.ToolTip = "Перетащите группу в другую зону.";
            Point start = new Point(), canvasStart = new Point();
            bool candidate = false;
            group.Grip.PreviewMouseLeftButtonDown += delegate(object sender, MouseButtonEventArgs e)
            {
                FreeCanvasBoard currentCanvas = group.Card.Parent as FreeCanvasBoard;
                if (!canEdit() || (board == null && !canvasAttached) ||
                    (currentCanvas != null && (currentCanvas.IsTemporaryLayout ||
                        (currentCanvas.CanEdit != null && !currentCanvas.CanEdit())))) return;
                start = e.GetPosition(group.Grip);
                if (currentCanvas != null) canvasStart = e.GetPosition(currentCanvas);
                candidate = group.Grip.CaptureMouse();
                e.Handled = true;
            };
            group.Grip.PreviewMouseLeftButtonUp += delegate
            { candidate = false; if (group.Grip.IsMouseCaptured) group.Grip.ReleaseMouseCapture(); };
            group.Grip.LostMouseCapture += delegate { candidate = false; };
            group.Grip.PreviewMouseMove += delegate(object sender, MouseEventArgs e)
            {
